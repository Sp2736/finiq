function generateMonthlyReturns(seed: number, volatility: number = 2.4, meanReturn: number = 1.2) {
  const years = [2026, 2025, 2024, 2023];
  const list: { date: string; returns: string }[] = [];

  years.forEach((yr) => {
    const maxMonth = yr === 2026 ? 10 : 12;
    for (let m = maxMonth; m >= 1; m--) {
      const monthStr = m < 10 ? `0${m}` : `${m}`;
      const day = m === 2 ? 28 : [4, 6, 9, 11].includes(m) ? 30 : 31;
      const pseudo = Math.sin(seed * 719 + yr * 17 + m * 31);
      const val = (pseudo * volatility + meanReturn).toFixed(2);
      list.push({
        date: `${yr}-${monthStr}-${day}`,
        returns: val,
      });
    }
  });

  return list;
}

